-- Exercise real hook installation and Jive's volume/power refresh ordering.
local f=assert(io.open('applet/StandaloneRadio/StreamPlayer.lua'))
local source=f:read('*a');f:close()
local hooks=assert(source:match('(function StreamPlayer:_installHooks%b().-)function StreamPlayer:_begin'))
StreamPlayer={}
assert(loadstring(hooks))()
local ticks,power,calls=0,'on',0
Framework={getTicks=function() return ticks end}
jiveMain={getSoftPowerState=function() return power end}
package.preload['applets.StandaloneBase.ServerMigration']=function() return {LOCAL_UUID='base'} end
local base={id='base',getIpPort=function() return '127.0.0.1',9000 end}
local remote={id='other',getIpPort=function() return '192.168.1.10',9000 end}
local server=base
local playback={_streamHttpHeaders=function() end,_streamDisconnect=function() end,
    slimproto={send=function() end}}
playback.sequenceNumber=0
local volume=28
local pending={}
local player={playback=playback,getSlimServer=function() return server end,
    getVolume=function() return volume end,getCurrentSequenceNumber=function() return playback.sequenceNumber end,
    refreshLocallyMaintainedParameters=function()
        calls=calls+1
        pending[#pending+1]=playback.sequenceNumber -- volume snapshot precedes sequenced power update
        playback.sequenceNumber=playback.sequenceNumber+1
        pending[#pending+1]=playback.sequenceNumber
    end}
Player={getLocalPlayer=function() return player end}
appletManager={loadApplet=function() return nil end}
local records={}
local owner={epoch=1,canStart=function() return true end}
local stream=setmetatable({ownership=owner,ownershipHooks={record=function(_,target,key,original)
    records[#records+1]={target=target,key=key,original=original};return true
end},log={info=function() end}}, {__index=StreamPlayer})
local original=player.refreshLocallyMaintainedParameters
stream:_installHooks(playback)
local wrapped=player.refreshLocallyMaintainedParameters
stream:_installHooks(playback)
assert(player.refreshLocallyMaintainedParameters==wrapped)
player:refreshLocallyMaintainedParameters()
-- Deliver every queued snapshot, including snapshots generated by refresh itself.
local delivered=0
while #pending>0 do
    delivered=delivered+1;assert(delivered<10,'Stale snapshots must converge, not amplify')
    local received=table.remove(pending,1)
    if received~=playback.sequenceNumber then player:refreshLocallyMaintainedParameters() end
end
assert(calls==1 and playback.sequenceNumber==1)
for _=1,100 do player:refreshLocallyMaintainedParameters() end
assert(calls==1,'Unchanged state must not flood the Base request queue')
volume=29;player:refreshLocallyMaintainedParameters();assert(calls==2)
power='off';player:refreshLocallyMaintainedParameters();assert(calls==3)
playback.sequenceNumber=playback.sequenceNumber+1;player:refreshLocallyMaintainedParameters();assert(calls==4)
ticks=2000;player:refreshLocallyMaintainedParameters();assert(calls==5,'Lost updates may retry')
server=remote
player:refreshLocallyMaintainedParameters();player:refreshLocallyMaintainedParameters()
assert(calls==7,'External LMS behavior must remain unchanged')
server=base;player:refreshLocallyMaintainedParameters();assert(calls==8)
local restored=false
for _,r in ipairs(records) do
    if r.key=='refreshLocallyMaintainedParameters' then
        assert(r.original==original);r.target[r.key]=r.original;restored=true
    end
end
assert(restored and player.refreshLocallyMaintainedParameters==original)
print('Local Base parameter feedback converges; real changes, retries and external servers pass through')

server=base;player.refreshLocallyMaintainedParameters=wrapped
player.state={seq_no=4000};playback.sequenceNumber=0
player:refreshLocallyMaintainedParameters()
assert(playback.sequenceNumber==4001,'A restarted firmware counter must catch up with the surviving Base')

-- An idle Radio still arms the compatibility hook when LocalPlayer appears.
local watchdog=assert(source:match('(function StreamPlayer:_watchdogTick%b().-)function StreamPlayer:_cancelReconnect'))
assert(loadstring(watchdog))()
local installed=0
local idle=setmetatable({_installHooks=function(_,value) assert(value==playback);installed=installed+1 end,
    _standbyFence=function() return false end,_resetWatchdog=function() end}, {__index=StreamPlayer})
idle:_watchdogTick()
assert(installed==1,'Idle startup must install parameter synchronization before a station is played')
