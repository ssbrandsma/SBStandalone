local parser=require("applets.StandaloneRadio.OpmlParser")
local function parse(xml,limits) return parser.parse(xml,limits) end
local function doc(text) return '<opml><head><title>Radio</title></head><body>'..text..'</body></opml>' end
local simple=assert(parse(doc('<outline type="audio" text="Caf&#233; &amp; Radio" URL="http://example.com/live?a=1&amp;b=2" />')))
assert(simple.children[1].title=="Caf\195\169 & Radio")
assert(simple.children[1].url=="http://example.com/live?a=1&b=2")
local nested=assert(parse(doc('<outline text="Folder"><outline type="link" URL="https://example.com/category" text="Remote" /></outline><outline text="Empty" />')))
assert(nested.children[1].children[1].type=="link" and nested.children[2].type=="directory")
local missing=assert(parse(doc('<outline/><outline type="audio"/><outline type="text" text="Heading"/>')))
assert(not missing.children[2].url and missing.children[3].type=="text")
local unicode=assert(parse(doc('<outline text="\230\151\165\230\156\172\232\170\158" TYPE="audio" Url="https://example.com/live" FORMATS="mp3" />')))
assert(unicode.children[1].type=="audio" and unicode.children[1].formats=="mp3")
assert(not parse(''))
assert(not parse('<opml><body>'))
assert(not parse('<html><body/></html>'))
assert(not parse('<!DOCTYPE opml [<!ENTITY x "secret">]><opml><body/></opml>'))
assert(not parse(doc(string.rep('<outline/>',20)),{nodes=10}))
assert(not parse(doc(string.rep('<outline>',40)..string.rep('</outline>',40))))
assert(not parse(doc('<outline/>'),{bytes=8}))
assert(not parse('<opml><head><status>403</status></head><body/></opml>'))
local f=assert(io.open('test/fixtures/opml/tunein-search.opml','rb'));local search=assert(parse(f:read('*a')));f:close()
local station=search.children[1]
assert(station.type=="audio" and station.guide_id=="s329637")
assert(station.bitrate==192 and station.formats=="mp3" and station.image:match("^http"))
assert(station.subtext and station.preset_id=="s329637" and station.now_playing_id=="s329637")
local root=assert(io.open('test/fixtures/opml/tunein-root.opml','rb'));local directory=assert(parse(root:read('*a')));root:close()
assert(#directory.children>=5 and directory.children[1].type=="link")
print("OPML real XML, Unicode/entities, nesting, missing fields, provider fixtures, malformed/access errors and allocation limits passed")
